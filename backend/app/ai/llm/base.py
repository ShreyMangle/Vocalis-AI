"""
app/ai/llm/base.py — Abstract Base Class for LLM Providers

Defines standard types and contracts for LLM completions, streaming, and tool calls.
Supports:
  - Groq (Llama-3.3-70b-versatile, Llama-3.1-8b-instant — free tier)
  - Google Gemini (gemini-2.0-flash — free tier)
  - OpenAI (GPT-4o, GPT-4o-mini)
  - Anthropic (Claude 3.5 Haiku / Sonnet)
  - Multi-provider resilient fallback chains
"""

from abc import ABC, abstractmethod
from collections.abc import AsyncIterator
from dataclasses import dataclass, field
from typing import Any


@dataclass
class LLMMessage:
    """Standard message representation across all providers."""

    role: str  # "system" | "user" | "assistant" | "tool"
    content: str | None = ""
    name: str | None = None
    tool_calls: list[dict[str, Any]] | None = None
    tool_call_id: str | None = None

    def to_dict(self) -> dict[str, Any]:
        d: dict[str, Any] = {
            "role": self.role,
            "content": self.content if self.content is not None else "",
        }
        if self.name:
            d["name"] = self.name
        if self.tool_calls:
            d["tool_calls"] = self.tool_calls
        if self.tool_call_id:
            d["tool_call_id"] = self.tool_call_id
        return d


@dataclass
class LLMResponse:
    """Standard response from any LLM provider."""

    content: str
    provider: str
    model: str
    tool_calls: list[dict[str, Any]] = field(default_factory=list)
    latency_ms: int = 0
    prompt_tokens: int = 0
    completion_tokens: int = 0


@dataclass
class LLMStreamChunk:
    """Incremental chunk yielded during token + tool-call streaming."""

    text_delta: str = ""
    tool_calls: list[dict[str, Any]] = field(default_factory=list)
    done: bool = False
    provider: str = ""
    model: str = ""
    latency_ms: int = 0
    finish_reason: str | None = None


class BaseLLMProvider(ABC):
    """Abstract interface that every LLM provider must implement."""

    def __init__(self, model: str, temperature: float = 0.3):
        self.model = model
        self.temperature = temperature

    @abstractmethod
    async def complete(
        self,
        messages: list[LLMMessage],
        tools: list[dict[str, Any]] | None = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """Execute a non-streaming completion."""
        pass

    @abstractmethod
    async def stream(
        self,
        messages: list[LLMMessage],
        tools: list[dict[str, Any]] | None = None,
        **kwargs: Any,
    ) -> AsyncIterator[str]:
        """Stream response text tokens as they are generated by the model."""
        pass

    async def stream_events(
        self,
        messages: list[LLMMessage],
        tools: list[dict[str, Any]] | None = None,
        **kwargs: Any,
    ) -> AsyncIterator[LLMStreamChunk]:
        """Stream structured text and tool-call chunks; subclasses override for native tool streaming."""
        async for chunk in self.stream(messages, tools, **kwargs):
            if chunk:
                yield LLMStreamChunk(
                    text_delta=chunk,
                    model=self.model,
                )
        yield LLMStreamChunk(done=True, model=self.model)
